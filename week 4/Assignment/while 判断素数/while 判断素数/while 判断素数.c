/*
## 题 4：while 判断素数
用 while 循环，输入一个数，判断是不是素数。是打印 "素数"，不是打印 "不是素数"。
*/
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main(void)
{
    int n;
    int i = 2;        // 除数，从 2 开始试（1 谁都能整除，试了没意义）
    int isPrime = 1;  // 标记：1 = 先假设是素数；0 = 被推翻，不是素数

    printf("请输入一个整数：");
    scanf("%d", &n);

    // 合法性检查：素数必须大于 1
    if (n <= 1) {
        printf("输入不合法，应输入大于1的数。\n");
        return 1;   // 结束程序，不再往下走
    }

    // ===== 核心循环：从 2 试到 n-1，找有没有能整除 n 的 =====
    while (i < n) {           // 只试到 n-1（n 被自己整除是正常的，不算数）
        if (n % i == 0) {     // n 能被 i 整除？说明找到了一个因子
            isPrime = 0;      // 推翻假设：不是素数
            break;            // 证据已找到，不用再试，立刻退出循环
        }
        i++;                  // 没整除，换下一个除数继续试
    }

    // 根据标记输出结果
    if (isPrime == 1) {       // 全程没找到因子 → 假设没被推翻，是素数
        printf("素数\n");
    }
    else {                    // 被推翻过 → 不是素数
        printf("不是素数\n");
    }

    return 0;
}