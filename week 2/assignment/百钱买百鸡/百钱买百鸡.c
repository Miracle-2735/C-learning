/*### 练习 2（标准版）：百钱买百鸡
- 公鸡 5 元一只，母鸡 3 元一只，小鸡 1 元三只
- 用 100 元买 100 只鸡，问各买多少只
- 用循环枚举所有可能，输出所有答案
- 提示：公鸡最多 20 只，母鸡最多 33 只，小鸡 = 100 - 公鸡 - 母鸡*/
#include <stdio.h>

int main()
{
	// i = 公鸡数量，j = 母鸡数量
	for (int i = 0; i <= 20; i++) {       // 公鸡最多20只
		for (int j = 0; j <= 33; j++) {   // 母鸡最多33只
			int k = 100 - i - j;          // 小鸡数量，直接算出来

			// 两个条件都满足才是答案：
			// ① 小鸡数量必须是3的倍数（因为1元3只，不能买1只半）
			// ② 总花费正好是100元
			if (k % 3 == 0 && 5 * i + 3 * j + k / 3 == 100) {
				printf("公鸡%d只，母鸡%d只，小鸡%d只\n", i, j, k);
			}
		}
	}

	return 0;
}