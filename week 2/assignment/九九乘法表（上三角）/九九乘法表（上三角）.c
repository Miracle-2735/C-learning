/*### 练习 1（超简版）：九九乘法表（上三角）
- 输出九九乘法表的上三角部分
- 格式：`1*1=1  1*2=2  ...  1*9=9`
- 只需要两层 for 循环*/
#include <stdio.h>

int main()
{
	// ===== 上三角 =====
	// 外层 i：第几行
	for (int i = 1; i <= 9; i++) {
		// 内层 j：第 i 行从 j=i 开始打印到 j=9
		// 比如第1行 j=1~9，第2行 j=2~9
		for (int j = i; j <= 9; j++) {
			printf("%d*%d=%d  ", i, j, i * j);
		}
		printf("\n");   // 一行打完换行
	}

	printf("\n");   // 两个三角形之间空一行

	// ===== 下三角 =====
	for (int i = 1; i <= 9; i++) {
		// 内层 j：第 i 行从 j=1 打印到 j=i
		// 比如第1行 j=1，第2行 j=1~2，第3行 j=1~3
		for (int j = 1; j <= i; j++) {
			printf("%d*%d=%d  ", j, i, i * j);
		}
		printf("\n");
	}

	return 0;
}